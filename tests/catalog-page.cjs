const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ channel:'chrome', headless:true });
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors = [];
    page.on('pageerror',error => errors.push(error.message));
    await page.route('**/*.supabase.co/**', route => route.abort());
    await page.goto('file://' + path.resolve(__dirname,'../outputs/index.html') + '#catalogArea');
    const ready = () => page.waitForFunction(() => document.querySelector('#catalog-results').getAttribute('aria-busy') === 'false');
    await ready();
    assert.equal(await page.locator('#catalogArea .card').count(),24);
    assert.match(await page.locator('#catalog-coverage').innerText(),/454,840/);
    const first = await page.locator('#catalogArea .card h2').first().innerText();
    await page.locator('#catalog-next').click(); await ready();
    assert.equal(await page.locator('#catalog-pageNumber').inputValue(),'2');
    assert.notEqual(await page.locator('#catalogArea .card h2').first().innerText(),first);
    await page.evaluate(()=>window.scrollTo({top:900,behavior:'instant'}));
    await page.waitForFunction(()=>JSON.parse(sessionStorage.getItem('card-ledger-catalog-view-v2')).scroll>=800);
    await page.locator('.side-nav [data-page-button="portfolio"]').click();
    await page.locator('.side-nav [data-page-button="catalog"]').click();
    await page.waitForFunction(()=>window.scrollY>=800);
    await page.reload();await ready();
    assert.equal(await page.locator('#catalog-pageNumber').inputValue(),'2');
    await page.waitForFunction(()=>window.scrollY>=800);
    await page.locator('#catalog-query').fill('Wembanyama Mosaic');
    await page.locator('#catalog-searchForm button[type=submit]').click(); await ready();
    assert.equal(await page.locator('#catalog-pageNumber').inputValue(),'1');
    assert.match(await page.locator('#catalogArea .card h2').first().innerText(),/Wembanyama/);
    await page.locator('#catalog-images').check(); await ready();
    assert.equal(await page.locator('#catalogArea .card img').count(),await page.locator('#catalogArea .card').count());
    await page.locator('#catalogArea .card img').first().evaluate(img => img.decode());
    await page.locator('#catalogArea .catalog-open-photo').first().click();
    assert.ok(await page.locator('#catalog-detail').evaluate(el => el.open));
    await page.locator('#catalog-close').click();
    await page.locator('#catalog-query').fill('zzzznotacard999999');
    await page.locator('#catalog-searchForm button[type=submit]').click(); await ready();
    assert.equal(await page.locator('#catalogArea .card').count(),0);
    assert.ok(await page.locator('#catalog-next').isDisabled());
    await page.locator('#catalog-clear').click(); await ready();
    await page.locator('#languageSelect').selectOption('zh-CN',{force:true}); await ready();
    assert.equal(await page.locator('#catalogTitle').innerText(),'卡片图鉴');
    assert.equal(await page.locator('#catalogArea').count(),1);
    assert.equal(await page.evaluate(() => document.body.dataset.activePage),'catalog');
    await page.screenshot({path:path.resolve(__dirname,'../work/catalog-desktop.png'),animations:'disabled'});
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(() => document.querySelector('#catalogArea').getBoundingClientRect().width >= innerWidth-32);
    await page.screenshot({path:path.resolve(__dirname,'../work/catalog-mobile.png'),animations:'disabled'});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.route('http://127.0.0.1:8765/**',route => route.abort());
    await page.locator('#catalog-searchForm button[type=submit]').click(); await ready();
    assert.ok(await page.locator('#catalog-error').isVisible());
    await page.evaluate(() => {
      account = {email:'catalog-section@example.invalid',name:'Catalog Test',role:'admin'};
      saveAccount(); render();
    });
    await page.locator('#catalog-batchUpload').click();
    assert.ok(await page.locator('#libraryBatchPane').isVisible());
    assert.equal(await page.evaluate(() => account.email),'catalog-section@example.invalid');
    await page.locator('.side-nav [data-page-button="catalog"]').click();
    assert.ok(await page.locator('#catalogArea').isVisible());
    assert.match(page.url(),/index\.html/);
    await page.goto('file://' + path.resolve(__dirname,'../outputs/catalog.html'));
    await page.waitForURL('**/index.html#catalogArea');
    await page.waitForFunction(() => document.body.dataset.activePage === 'catalog');
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('PASS: full catalog, pagination, search, image-only filter, preview, empty state, Chinese, mobile layout and offline state.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
