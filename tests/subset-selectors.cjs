const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try {
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*.supabase.co/**',route=>route.abort());
  await page.goto('file://'+path.resolve(__dirname,'../outputs/index.html'));
  await page.waitForFunction(()=>window.CardLedgerSubsets);
  await page.evaluate(()=>{account={name:'Subset Test',email:'subsets@example.invalid',role:'admin'};saveAccount();render();setActivePage('collection');setFocusWorkspaceView('collection','add',{scroll:false});});
  await page.locator('#sport').selectOption('Basketball');
  await page.locator('#hciYearPicker').selectOption('2018');
  await page.locator('#brand').selectOption('Panini');
  await page.locator('#setName').selectOption('Donruss Optic');
  const options=await page.locator('#insertNamePicker option').evaluateAll(items=>items.map(item=>item.value));
  assert.ok(options.includes('All Heart'));assert.ok(options.includes('Express Lane'));assert.ok(options.includes('__custom__'));
  await page.locator('#insertNamePicker').selectOption('All Heart');
  assert.equal(await page.locator('#insertName').inputValue(),'All Heart');
  assert.equal(await page.locator('#insertName').isVisible(),false);
  assert.equal(await page.evaluate(()=>buildCardFromForm().insertName),'All Heart');
  await page.locator('#insertNamePicker').selectOption('__custom__');
  await page.locator('#insertName').fill('My Missing Insert');
  await page.evaluate(()=>CardLedgerSubsets.refresh());
  assert.equal(await page.locator('#insertNamePicker').inputValue(),'__custom__');
  assert.equal(await page.locator('#insertName').inputValue(),'My Missing Insert');
  await page.locator('#insertNamePicker').selectOption('All Heart');
  await page.locator('#hciYearPicker').selectOption('2023');
  assert.equal(await page.locator('#insertName').inputValue(),'');
  await page.locator('#brand').selectOption('Panini');
  await page.locator('#setName').selectOption('Prizm');
  const prizm=await page.locator('#insertNamePicker option').evaluateAll(items=>items.map(item=>item.value));
  assert.ok(prizm.includes('Dominance'));
  assert.ok(!prizm.some(value=>value.startsWith('Draft Picks')||value.startsWith('Deca')));
  await page.evaluate(()=>{cards=[{id:'custom-subset',year:'2018',sport:'Basketball',brand:'Panini',setName:'Donruss Optic',player:'Jimmy Butler',insertName:'Collector Custom Insert',quantity:1,paid:0,value:0}];saveCards();editCard(cards[0].id);});
  assert.equal(await page.locator('#insertNamePicker').inputValue(),'__custom__');
  assert.equal(await page.locator('#insertName').inputValue(),'Collector Custom Insert');
  await page.evaluate(()=>{CardLedgerLibrary.review('',[],{sport:'Basketball',year:'2018',brand:'Panini',setName:'Donruss Optic',player:'Jimmy Butler',insertName:'All Heart'},()=>{});});
  await page.waitForSelector('#libraryReviewSubsetPicker');
  assert.equal(await page.locator('#libraryReviewSubsetPicker').inputValue(),'All Heart');
  await page.locator('#libraryReviewSubsetPicker').selectOption('__custom__');
  await page.locator('#libraryReview-insertName').fill('Another Insert');
  await page.locator('#libraryReview-year').fill('2024');
  assert.equal(await page.locator('#libraryReview-insertName').inputValue(),'Another Insert');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#libraryReviewSubsetPicker').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.resolve(__dirname,'../work/subset-selector-mobile.png'),animations:'disabled'});
  assert.ok(await page.locator('.library-dialog').evaluate(element=>element.scrollWidth<=element.clientWidth+1));
  assert.deepEqual(errors,[]);
  console.log('PASS: year/brand/set-filtered HCI subset choices, product exclusion, known selection, manual fallback, context reset, custom edit preservation and scan review/mobile integration.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
