-- Marketplace connection metadata and shared PSA population index.
-- Apply after card-ledger-profiles.sql and card-ledger-data.sql.
-- Provider secrets belong in Supabase Edge Function secrets, never these tables.

create extension if not exists pg_trgm with schema extensions;

alter table public.cards add column if not exists certification text not null default '';
alter table public.cards add column if not exists psa_population jsonb;

create table if not exists public.marketplace_connections (
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null check (provider in ('ebay', 'cardhobby')),
  status text not null default 'disconnected' check (status in ('disconnected', 'configured', 'connected', 'error')),
  external_account_label text not null default '',
  capabilities jsonb not null default '[]'::jsonb check (jsonb_typeof(capabilities) = 'array'),
  last_checked_at timestamptz,
  last_error text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, provider)
);

create table if not exists public.psa_population_records (
  id bigint generated by default as identity primary key,
  identity_key text not null,
  psa_spec_id bigint,
  year text not null default '',
  brand text not null default '',
  set_name text not null default '',
  subject text not null default '',
  card_number text not null default '',
  variety text not null default '',
  category text not null default '',
  grade numeric(3, 1) not null check (grade >= 0 and grade <= 10),
  grade_label text not null default '',
  population_at_grade integer not null default 0 check (population_at_grade >= 0),
  population_higher integer not null default 0 check (population_higher >= 0),
  population_total integer check (population_total is null or population_total >= 0),
  sample_cert_number text not null default '',
  source_type text not null default 'psa_public_api' check (source_type in ('psa_public_api', 'psa_population_page', 'admin_import')),
  source_url text not null,
  source_updated_at timestamptz,
  fetched_at timestamptz not null default now(),
  raw_payload jsonb not null default '{}'::jsonb check (jsonb_typeof(raw_payload) = 'object'),
  unique (identity_key, grade)
);

alter table public.psa_population_records add column if not exists psa_spec_id bigint;

create index if not exists psa_population_identity_idx on public.psa_population_records (identity_key, grade desc);
create index if not exists psa_population_spec_idx on public.psa_population_records (psa_spec_id) where psa_spec_id is not null;
create index if not exists psa_population_subject_trgm_idx on public.psa_population_records using gin (lower(subject) extensions.gin_trgm_ops);
create index if not exists psa_population_set_trgm_idx on public.psa_population_records using gin (lower(set_name) extensions.gin_trgm_ops);
create index if not exists psa_population_card_number_idx on public.psa_population_records (card_number);
create index if not exists psa_population_fetched_idx on public.psa_population_records (fetched_at desc);

alter table public.marketplace_connections enable row level security;
alter table public.psa_population_records enable row level security;

drop policy if exists marketplace_connections_owner_select on public.marketplace_connections;
create policy marketplace_connections_owner_select on public.marketplace_connections
for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists marketplace_connections_owner_insert on public.marketplace_connections;
create policy marketplace_connections_owner_insert on public.marketplace_connections
for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists marketplace_connections_owner_update on public.marketplace_connections;
create policy marketplace_connections_owner_update on public.marketplace_connections
for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists marketplace_connections_owner_delete on public.marketplace_connections;
create policy marketplace_connections_owner_delete on public.marketplace_connections
for delete to authenticated using ((select auth.uid()) = user_id);

drop policy if exists psa_population_authenticated_read on public.psa_population_records;
create policy psa_population_authenticated_read on public.psa_population_records
for select to authenticated using (true);

revoke all on public.marketplace_connections from anon, authenticated;
grant select, insert, update, delete on public.marketplace_connections to authenticated;
revoke all on public.psa_population_records from anon, authenticated;
grant select on public.psa_population_records to authenticated;

create or replace function public.search_psa_population(
  search_text text default '',
  result_limit integer default 25
)
returns setof public.psa_population_records
language sql
stable
security invoker
set search_path = ''
as $$
  select population.*
  from public.psa_population_records population
  where trim(search_text) = ''
    or not exists (
      select 1
      from regexp_split_to_table(lower(trim(search_text)), '\s+') as query_token
      where query_token <> ''
        and position(query_token in lower(concat_ws(' ', population.year, population.brand, population.set_name, population.subject, population.card_number, population.variety, population.grade_label))) = 0
    )
  order by
    case when lower(population.subject) = lower(trim(search_text)) then 0 else 1 end,
    population.fetched_at desc,
    population.grade desc
  limit least(greatest(result_limit, 1), 100);
$$;

revoke all on function public.search_psa_population(text, integer) from public, anon;
grant execute on function public.search_psa_population(text, integer) to authenticated;

